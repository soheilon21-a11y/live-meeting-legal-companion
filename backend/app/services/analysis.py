import json
import logging
import re

import httpx

from app.core.config import settings
from app.services import retrieval
from app.services.live_worker import model_lock

VALID_STATUSES = {"supported", "conflicting", "insufficient"}

# Reject absurdly large fields so a runaway model output cannot be persisted.
MAX_PASSAGE_CHARS = 8000
MAX_QUESTION_CHARS = 1000

logger = logging.getLogger(__name__)


def normalize(text: str) -> str:
    """Canonical whitespace normalization shared by grounding validation.

    The document-ingestion pipeline keeps raw extracted text (it does not
    collapse whitespace), so grounding is a whitespace-normalized substring
    containment against the retrieved chunk text — not a byte-for-byte
    character-for-character equality against the original binary document.
    """
    return " ".join((text or "").split())


def _match_passage(verbatim: str, passages: list[dict]) -> dict | None:
    """Return the first retrieved passage containing ``verbatim`` (normalized).

    Passage metadata is generated by the backend during ingestion, so both the
    grounding check and the reported position derive from retrieval order
    instead of model output.
    """
    needle = normalize(verbatim)
    if not needle:
        return None
    for passage in passages:
        if needle in normalize(passage.get("text", "")):
            return passage
    return None


def _build_prompt(discussion_point: str, passages: list[dict]) -> str:
    lines = [f"[{i}] {p['position']}: {p['text']}" for i, p in enumerate(passages, 1)]
    context = "\n\n".join(lines)
    return (
        "You are a retrieval assistant for a legal meeting. You are NOT a legal "
        "adviser and must NOT give legal advice, reach legal conclusions, or "
        "recommend a course of action. Use ONLY the retrieved passages below; "
        "never invent a name, date, amount, statute, clause, or fact that is not "
        "present in them. Do not phrase a question in a way that presupposes an "
        "unsupported fact. All output is a draft a human lawyer must review.\n\n"
        f"RETRIEVED PASSAGES (verbatim from the source document):\n{context}\n\n"
        f"DISCUSSION POINT: {discussion_point}\n\n"
        "Answer as a single JSON object with exactly these keys:\n"
        '- "verbatim_passage": copy the single most relevant passage character-for-character '
        "from the passages above (empty string if none relevant).\n"
        '- "issue_question": the issue stated narrowly as a question (never a conclusion).\n'
        '- "evidence_status": "supported", "conflicting", or "insufficient".\n'
        '- "suggested_question": one question the lawyer may raise in the meeting '
        "(empty string if none).\n"
        'If no passage is relevant, set "evidence_status" to "insufficient" and '
        '"verbatim_passage" to "". Respond in the language of the discussion point.'
    )


def _call_llm(prompt: str) -> tuple[str, dict | None]:
    """Return ``(response_text, usage_metadata)`` from one Ollama call.

    Usage is captured inside the same call that produced the response and is
    request-scoped: no module-global token counter is shared across requests.
    """
    resp = httpx.post(
        f"{settings.OLLAMA_BASE_URL}/api/generate",
        json={
            "model": settings.MODEL_NAME,
            "prompt": prompt,
            "stream": False,
            "format": "json",
            "options": {
                "temperature": settings.LLM_TEMPERATURE,
                "num_predict": settings.LLM_MAX_TOKENS,
            },
        },
        timeout=settings.LLM_TIMEOUT,
    )
    resp.raise_for_status()
    data = resp.json()
    usage = {
        "model": data.get("model", settings.MODEL_NAME),
        "prompt_tokens": data.get("prompt_eval_count"),
        "completion_tokens": data.get("eval_count"),
    }
    return data.get("response", ""), usage


def _parse_response(raw: str) -> dict:
    raw = (raw or "").strip()
    try:
        data = json.loads(raw)
        if isinstance(data, dict):
            return data
    except json.JSONDecodeError:
        pass
    match = re.search(r"\{.*\}", raw, re.DOTALL)
    if match:
        try:
            data = json.loads(match.group(0))
            if isinstance(data, dict):
                return data
        except json.JSONDecodeError:
            pass
    return {}


def _validate_finding(data: dict, passages: list[dict]) -> tuple[bool, str]:
    """Strict, proportionate validation of an LLM finding.

    Returns ``(ok, reason)``. A non-empty ``verbatim_passage`` must be
    whitespace-normalized verbatim in a retrieved passage. The model's
    ``passage_position`` is never treated as evidence; the backend derives it
    from the matched passage after validation.
    """
    if not isinstance(data, dict):
        return False, "output is not a JSON object"

    verbatim = data.get("verbatim_passage")
    issue = data.get("issue_question")
    status = data.get("evidence_status")
    suggested = data.get("suggested_question")

    # Field types.
    if not isinstance(verbatim, str):
        return False, "verbatim_passage is not a string"
    if not isinstance(issue, str):
        return False, "issue_question is not a string"
    if status not in VALID_STATUSES:
        return False, f"invalid evidence_status {status!r}"
    if suggested is not None and not isinstance(suggested, str):
        return False, "suggested_question is not a string"

    # Reasonable size limits.
    if len(verbatim) > MAX_PASSAGE_CHARS:
        return False, "verbatim_passage exceeds size limit"
    if len(issue) > MAX_QUESTION_CHARS:
        return False, "issue_question exceeds size limit"
    if suggested and len(suggested) > MAX_QUESTION_CHARS:
        return False, "suggested_question exceeds size limit"

    issue = issue.strip()
    if not issue:
        return False, "issue_question is empty"

    if not normalize(verbatim):
        # "No relevant passage" answer: the position is derived as null later.
        return True, ""

    # Non-empty quote must be present in a retrieved passage (normalized).
    if _match_passage(verbatim, passages) is None:
        return False, "verbatim_passage is not present in any retrieved passage"

    return True, ""


def _empty_finding() -> dict:
    return {
        "verbatim_passage": "",
        "passage_position": None,
        "issue_question": "",
        "evidence_status": "insufficient",
        "suggested_question": None,
        "source": "retrieval_only",
    }


def _retrieval_only_finding(passages: list[dict]) -> dict:
    top = passages[0]
    return {
        "verbatim_passage": top["text"],
        "passage_position": top["position"],
        "issue_question": "",
        "evidence_status": "insufficient",
        "suggested_question": None,
        "source": "retrieval_only",
    }


def analyze(
    document_id: str,
    discussion_point: str,
    transcript_excerpt: str | None = None,
) -> tuple[dict, str]:
    query = discussion_point
    if transcript_excerpt:
        query = f"{transcript_excerpt}\n{discussion_point}"
    passages = retrieval.retrieve(document_id, query)
    if not passages:
        return _empty_finding(), "retrieval_only"

    prompt = _build_prompt(discussion_point, passages)
    # LLM_MAX_RETRIES is the number of retries; one initial attempt is always
    # made, so the total is 1 + retries. A zero/negative value still yields at
    # least one model call.
    total_attempts = max(1, settings.LLM_MAX_RETRIES + 1)
    last_error: str | None = None
    for attempt in range(total_attempts):
        try:
            with model_lock:
                raw, usage = _call_llm(prompt)
            data = _parse_response(raw)
            ok, reason = _validate_finding(data, passages)
            if ok:
                # Position comes only from backend retrieval metadata; the
                # model-supplied position (if any) is ignored.
                matched = _match_passage(data.get("verbatim_passage") or "", passages)
                return {
                    "verbatim_passage": (data.get("verbatim_passage") or "").strip(),
                    "passage_position": matched["position"] if matched else None,
                    "issue_question": (data.get("issue_question") or "").strip(),
                    "evidence_status": data.get("evidence_status"),
                    "suggested_question": data.get("suggested_question") or None,
                    "source": "llm_grounded",
                    "usage": usage,
                }, "llm_grounded"
            last_error = reason
            logger.warning("LLM output rejected as %r (attempt %d)", reason, attempt + 1)
        except Exception as exc:  # noqa: BLE001 — bounded fallback below
            last_error = str(exc)
            logger.warning("LLM call failed (attempt %d): %s", attempt + 1, exc)

    logger.warning(
        "LLM fallback to retrieval-only after %d attempts: %s",
        total_attempts,
        last_error,
    )
    return _retrieval_only_finding(passages), "retrieval_only"
